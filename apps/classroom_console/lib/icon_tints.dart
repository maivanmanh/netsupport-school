    final names = <String, IconData>{
      for (final e in _iconsByName.entries) e.key: e.value,
    };
    final result = <int, Color>{};
    _families.forEach((color, list) {
      for (final name in list) {
        final icon = names[name];
        if (icon != null) result[icon.codePoint] = color;
      }
    });
    return result;
