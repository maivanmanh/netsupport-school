/// An [Icon] that, unless given a colour, takes the tint for its glyph.
class TIcon extends Icon {
  const TIcon(
    super.icon, {
    super.key,
    super.size,
    super.color,
    super.semanticLabel,
  });

  @override
  Widget build(BuildContext context) {
    if (color != null || icon == null || _onSolidButton(context)) {
      return super.build(context);
    }
    // Tint through the icon theme so this stays a single Icon in the tree.
    return IconTheme.merge(
      data: IconThemeData(color: IconTints.of(icon!)),
      child: Builder(builder: (inner) => super.build(inner)),
    );
  }
}

/// True inside a filled (solid-background) button, where the button's own
/// foreground colour is what keeps the glyph readable.
bool _onSolidButton(BuildContext context) {
  var solid = false;
  context.visitAncestorElements((element) {
    final widget = element.widget;
    if (widget is ButtonStyleButton) {
      solid = widget is FilledButton;
      return false;
    }
    return true;
  });
  return solid;
}

